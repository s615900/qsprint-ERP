// Plain-text version of a template, for fields that don't take HTML (quote terms).
export function htmlToText(html: string): string {
  return html
    .replace(/<\/(p|li|ol|ul)>/gi, "\n")
    .replace(/<li>/gi, "• ")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
